/* ---------- Export Directory (PDF) ---------- */
function directoryExportData(){
    const placed = placementList();
    const head = ['Company', 'Industry', 'HR / supervisor contact', 'MOA valid until', 'MOA status', 'Days left', 'MOA scan in vault', 'Interns deployed', 'In process', 'Partner account'];
    const rows = partnerCompanies().map(c => {
        const info = partnerInfo(c), status = moaStatus(info.moaUntil)[0];
        const days = info.moaUntil ? Math.round((new Date(info.moaUntil) - new Date(todayISO())) / 864e5) : '';
        const deployed = placed.filter(p => p.company === c && ['Deployed', 'Hours complete'].includes(p.status)).length;
        const inProcess = placed.filter(p => p.company === c && ['Applied', 'Endorsed', 'Accepted'].includes(p.status)).length;
        return [c, info.industry || '', info.hr || '', info.moaUntil || '', status, days, ensureVault(c).files.some(f => f.type === 'MOA / MOU') ? 'Yes' : 'No',
            deployed, inProcess, info.accounts.length ? info.accounts.map(a => a.email).join(', ') : 'None (coordinator-managed)'];
    });
    const count = (label) => rows.filter(r => r[4] === label).length;
    const me = getJSON('ic_session', null) || {};
    const details = [['Report', 'Partner company and MOA directory'], ['Batch (class code)', activeClassCode()], ['Generated on', todayISO()], ['Generated by', me.name || me.email || ''],
        ['Partner companies', rows.length], ['MOA active', count('Active')], ['MOA expiring within 90 days', count('Expiring Soon')], ['MOA expired', count('Expired')], ['No MOA date', count('No MOA date')],
        ['Without MOA scan in vault', rows.filter(r => r[6] === 'No').length], ['Interns deployed', rows.reduce((n, r) => n + r[7], 0)], ['Interns in process', rows.reduce((n, r) => n + r[8], 0)]];
    return {head, rows, details};
}
const directoryFile = () => 'Partner_MOA_Directory_' + fileSlug(activeClassCode() || 'batch') + '_' + todayISO() + '.pdf';
function exportDirectoryPdf(){
    const lib = window.jspdf && window.jspdf.jsPDF;
    const doc = lib && new lib({unit: 'pt', format: 'a4', orientation: 'landscape'});
    if(!doc || typeof doc.autoTable !== 'function'){ showToast('The PDF library could not load (are you offline?). Please try again later.', 'warn'); return false; }
    const d = directoryExportData(), det = Object.fromEntries(d.details);
    const css = getComputedStyle(document.documentElement);
    const rgb = (n, fb) => { const h = css.getPropertyValue(n).trim().replace('#', ''); return /^[0-9a-f]{6}$/i.test(h) ? [0, 2, 4].map(i => parseInt(h.substr(i, 2), 16)) : fb; };
    const dark = rgb('--bd', [15, 23, 42]), accent = rgb('--b600', [2, 132, 199]);
    const W = doc.internal.pageSize.getWidth(), H = doc.internal.pageSize.getHeight(), M = 40;
    const contentY = drawExportHeader(doc, 'Partner Company & MOA Directory', [
        det['Batch (class code)'] + '  -  ' + det['Partner companies'] + ' partners  -  ' + det['MOA active'] + ' active, ' + det['MOA expiring within 90 days'] + ' expiring, ' + det['MOA expired'] + ' expired',
        'Generated ' + det['Generated on'] + (det['Generated by'] ? ' by ' + det['Generated by'] : '')
    ], M);
    doc.autoTable({startY: contentY, margin: {left: M, right: M, bottom: 44}, theme: 'striped',
        head: [['Company', 'HR contact', 'MOA valid until', 'MOA status', 'Scan in vault', 'Deployed', 'In process']],
        body: d.rows.length ? d.rows.map(r => [r[0] + (r[1] ? '\n' + r[1] : ''), r[2] || '-', r[3] || '-', r[4], r[6], r[7], r[8]]) : [['No partner companies in this batch yet.', '', '', '', '', '', '']],
        styles: {fontSize: 9.5, cellPadding: 5, textColor: [30, 41, 59]}, headStyles: {fillColor: accent, textColor: 255, fontStyle: 'bold'}, alternateRowStyles: {fillColor: [248, 250, 252]},
        columnStyles: {4: {halign: 'center'}, 5: {halign: 'right'}, 6: {halign: 'right'}},
        didParseCell: (h) => { if(h.section === 'body' && h.column.index === 3){ const t = h.cell.raw; h.cell.styles.fontStyle = 'bold'; h.cell.styles.textColor = t === 'Expired' ? [220, 38, 38] : t === 'Expiring Soon' ? [217, 119, 6] : t === 'Active' ? [5, 150, 105] : [100, 116, 139]; } }});
    const pages = doc.getNumberOfPages();
    for(let i = 1; i <= pages; i++){ doc.setPage(i); doc.setFont('helvetica', 'normal'); doc.setFontSize(8); doc.setTextColor(120, 130, 145);
        doc.text('InternConnect  |  Partner & MOA directory  |  ' + det['Generated on'], M, H - 22); doc.text('Page ' + i + ' of ' + pages, W - M, H - 22, {align: 'right'}); }
    doc.save(directoryFile());
    return true;
}
function initCoordinatorDirectoryExport(){
    if(!document.getElementById('exportDirBtn')) return;
    const btn = document.getElementById('exportDirBtn');
    btn.addEventListener('click', () => {
        const label = 'PDF';
        try { if(!exportDirectoryPdf()) return; }
        catch(err){ console.error(err); showToast('Could not create the file. Please try again.', 'warn'); return; }
        logAudit('Exported the partner and MOA directory (' + label + ')');
        showToast('Partner & MOA directory downloaded as ' + label + '.', 'success');
    });
}
window.ICCore = window.ICCore || {};
window.ICCore.coordinator = window.ICCore.coordinator || {};
window.ICCore.coordinator.initDirectoryExport = initCoordinatorDirectoryExport;
